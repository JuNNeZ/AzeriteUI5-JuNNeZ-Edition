param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$name = 'AzeriteUI5_JuNNeZ_Edition'
$source = [IO.File]::ReadAllText((Join-Path $root "$name.toc"))

# Every generated TOC: path and expected text. -Check compares, otherwise they are written.
$targets = [ordered]@{}

# The Forever load entry: the base TOC with Forever's interface number.
$expected = $source -replace '(?m)^## Interface:.*', '## Interface: 16001'
$expected = "# Generated by Tools/BuildClientTOC.ps1; edit the base TOC instead.`n## X-AzeriteUI-Client: Forever`n" + $expected
$targets[(Join-Path $root "${name}_Camelot.toc")] = $expected.Replace("`r`n", "`n")

# The load-on-demand debug companion (Core/DebugLoader.lua loads it), one TOC per
# client, interface and version taken from the base TOC so they never drift.
$companion = "${name}_Debug"
$retailInterface = [regex]::Match($source, '(?m)^## Interface:\s*(.+?)\s*$').Groups[1].Value
$version = [regex]::Match($source, '(?m)^## Version:\s*(.+?)\s*$').Groups[1].Value
$icon = [regex]::Match($source, '(?m)^## IconTexture:\s*(.+?)\s*$').Groups[1].Value
if (-not $retailInterface -or -not $version) { throw 'Base TOC has no Interface or Version line.' }
$companionBody = @"
## Title: |cff4488bbAzerite|r |cfffafafaUI|r |cff00ff00JuNNeZ Edition|r Debug Tools
## Notes: /azdebug, its probes and the test menus. AzeriteUI loads this only when one is used.
## IconTexture: $icon
## Version: $version
## Author: JuNNeZ
## Dependencies: $name
## LoadOnDemand: 1
## X-License: Custom

Debugging.lua
AuraCostProbe.lua
RenderProbe.lua
ExecuteProbe.lua
"@
$header = "# Generated by Tools/BuildClientTOC.ps1; edit the base TOC or this script instead.`n"
$companionDir = Join-Path $root $companion
$targets[(Join-Path $companionDir "$companion.toc")] = ($header + "## Interface: $retailInterface`n" + $companionBody).Replace("`r`n", "`n")
$targets[(Join-Path $companionDir "${companion}_Camelot.toc")] = ($header + "## X-AzeriteUI-Client: Forever`n## Interface: 16001`n" + $companionBody).Replace("`r`n", "`n")

foreach ($target in $targets.Keys) {
    $text = $targets[$target]
    if ($Check) {
        if (-not (Test-Path -LiteralPath $target) -or [IO.File]::ReadAllText($target).Replace("`r`n", "`n") -cne $text) {
            throw "Generated TOC is out of date: $target. Run Tools/BuildClientTOC.ps1."
        }
    } else {
        [IO.File]::WriteAllText($target, $text, [Text.UTF8Encoding]::new($false))
    }
}
