"""Install complete, selectable WIP themes with exact source replay and failures retained."""
import argparse
import json

from PriestWarlockAssetContracts import ROOT, LONG, sha, record
from PriestWarlockPack import candidate, read
from ThemeSourceIntegrity import verify_pixels


def install(theme):
    files,records,evidence=candidate(theme)
    folder=ROOT/"Assets"/theme;data_path=ROOT/"Core"/(theme+"ThemeData.lua")
    old=json.loads((folder/"manifest.json").read_text()) if (folder/"manifest.json").exists() else None
    if data_path.exists():assert old and sha(data_path)==old["runtimeData"]["sha256"], "Runtime data edited outside this build"
    for path in folder.glob("*.tga") if folder.exists() else []:
        assert old and path.stem in old["assets"] and sha(path)==old["assets"][path.stem]["sha256"], "Existing art changed: "+str(path)
    folder.mkdir(parents=True,exist_ok=True)
    for name,image in files.items():
        path=folder/(name+".tga");image.save(path,compression=None);verify_pixels(image,read(path))
        records[name].update(record(path),canvas=list(image.size))
    footprint=json.loads((ROOT/"Docs/Research_Assets"/theme/"Contracts/approved-footprints.json").read_text())["cases"]
    motif="tuure" if theme=="Priest" else "ulthalesh"
    media=sorted(name for name in files if (ROOT/"Assets"/(name+".tga")).exists())
    dips={name:[footprint[name]["nativeToe"][0]/files[name].width,footprint[name]["nativeToe"][1]/files[name].height] for name in LONG}
    edges={name:files["ornament-"+motif+"-"+name].getchannel("A").point(lambda a:255 if a>128 else 0).getbbox()[0] for name in LONG}
    def mapping(values):
        return "{ "+", ".join('["'+key+'"] = '+("{ "+", ".join(map(str,value))+" }" if isinstance(value,list) else str(value)) for key,value in sorted(values.items()))+" }"
    data="-- Generated by Tools/Install-PriestWarlockPreview.py; WIP, live unverified.\nlocal _, ns = ...\nns."+theme+"ThemeData = {\n\tmedia = { "+", ".join('["'+name+'"] = true' for name in media)+" },\n\tdips = "+mapping(dips)+",\n\tedges = { "+motif+" = "+mapping(edges)+" }\n}\n"
    data_path.write_text(data,encoding="utf-8",newline="\n")
    manifest={"schema":1,"theme":theme,"installationMode":"user-authorized complete WIP preview",
        "authorization":"Fint, gør temaerne færdige; approved concepts and Druid maximum retained",
        "productionAccepted":False,"maintainerFullPackVisualApproved":False,"liveRetailValidated":False,"liveForeverValidated":False,
        "assets":records,"runtimeData":record(data_path),"evidence":evidence}
    (folder/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    print(theme+": installed "+str(len(files))+" exact-replay WIP textures, "+str(len(media))+" native media replacements; "+str(len(evidence["functionalFailures"]))+" numeric issues retained")


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("theme",choices=("Priest","Warlock","Both"));parser.add_argument("--live-preview",action="store_true");args=parser.parse_args()
    if not args.live_preview:parser.error("Only explicit WIP preview mode is supported; production approval is never inferred")
    for theme in ("Priest","Warlock") if args.theme=="Both" else (args.theme,):install(theme)
